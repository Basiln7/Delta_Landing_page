const order = (
  n: number,
  date: string,
  name: string,
  email: string,
  phone: string,
  items: Order["items"],
  paymentMethod: Order["paymentMethod"],
  status: Order["status"],
  coupon?: "DELTA10" | "LAUNCH20",
): Order => {
  const subtotal = items.reduce((s, i) => s + i.price, 0);
  const discount = coupon ? Math.round((subtotal * (coupon === "DELTA10" ? 10 : 20)) / 100) : 0;
  return {
    id: `or_${n}`,
    number: `DLT-${10000 + n}`,
    customer: { name, email, phone },
    items,
    subtotal,
    discount,
    total: subtotal - discount,
    coupon,
    currency: "INR",
    paymentMethod,
    status,
    createdAt: date,
  };
};

